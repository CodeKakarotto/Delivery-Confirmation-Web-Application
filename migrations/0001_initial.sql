-- Michael's Flowers delivery confirmation prototype: initial schema.
-- All timestamps are ISO-8601 UTC text (e.g. 2026-11-14T21:13:00.000Z). Delivery dates are YYYY-MM-DD.
-- D1 enforces foreign keys. See docs/SCHEMA.md and docs/INTEGRATION.md.
--
-- Intentionally absent: user accounts, logins, sessions, GPS/location tracking, route planning, a delivery
-- status workflow, payments, inventory and photo storage (out of scope for this prototype).

-- Orders that can be confirmed. Column names match the route-optimization app's `deliveries` table where the
-- two overlap (order_id, recipient_name, address_line, city, state, postal_code, delivery_notes), so the two
-- systems can later share one table. Columns that the route app does not have yet are NULLable and are never
-- invented: the app shows an em dash ("—") or "Not recorded" instead.
CREATE TABLE deliveries (
  id              INTEGER PRIMARY KEY AUTOINCREMENT,
  -- Existing order / FTD ticket number. Same rules as the route app.
  order_id        TEXT    NOT NULL UNIQUE COLLATE NOCASE CHECK (length(order_id) BETWEEN 1 AND 40),
  recipient_name  TEXT    CHECK (recipient_name IS NULL OR length(recipient_name) <= 100),
  address_line    TEXT    NOT NULL CHECK (length(address_line) BETWEEN 1 AND 200),
  city            TEXT    NOT NULL CHECK (length(city) BETWEEN 1 AND 80),
  state           TEXT    NOT NULL CHECK (length(state) BETWEEN 2 AND 2),
  postal_code     TEXT    NOT NULL CHECK (length(postal_code) BETWEEN 5 AND 10),
  -- Short notes about the address itself (suite, gate, building). Shown under Deliver To. Not in the route app.
  address_notes   TEXT    CHECK (address_notes IS NULL OR length(address_notes) <= 300),
  -- The route app's delivery_notes. Shown read-only as Delivery Instructions.
  delivery_notes  TEXT    CHECK (delivery_notes IS NULL OR length(delivery_notes) <= 1000),
  -- Delivery zone, when the shop has assigned one. No zone source exists in the route app yet: NULL = "—".
  zone            TEXT    CHECK (zone IS NULL OR length(zone) BETWEEN 1 AND 20),
  -- Total products/items on the order, from the order itself. NULL = not recorded (never calculated).
  total_products  INTEGER CHECK (total_products IS NULL OR total_products BETWEEN 1 AND 999),
  -- Stop number (#) on the driver's route (route app: route_stops.sequence_number). NULL = not on a route.
  stop_number     INTEGER CHECK (stop_number IS NULL OR stop_number BETWEEN 1 AND 999),
  -- The day the order is expected to be delivered. Used to list deliveries that still need a confirmation.
  delivery_date   TEXT    CHECK (delivery_date IS NULL OR delivery_date GLOB '[0-9][0-9][0-9][0-9]-[0-9][0-9]-[0-9][0-9]'),
  -- Cancelled orders cannot be confirmed (route app equivalent: deleted_at with reason order_canceled).
  cancelled_at    TEXT,
  created_at      TEXT    NOT NULL,
  updated_at      TEXT    NOT NULL
);
CREATE INDEX idx_deliveries_date ON deliveries(delivery_date);

-- One saved proof of delivery per order. Never updated or overwritten by the API.
CREATE TABLE delivery_confirmations (
  -- Random UUID generated by the server (not guessable from the order ID).
  id               TEXT    PRIMARY KEY CHECK (length(id) = 36),
  -- UNIQUE: an order can have only one confirmation. RESTRICT: an order with a confirmation cannot be deleted.
  delivery_id      INTEGER NOT NULL UNIQUE REFERENCES deliveries(id) ON DELETE RESTRICT,
  -- Snapshots taken by the server from the order at the moment of confirmation (not from the browser).
  order_id         TEXT    NOT NULL COLLATE NOCASE,
  stop_number      INTEGER,
  zone             TEXT,
  received_by      TEXT    NOT NULL CHECK (length(received_by) BETWEEN 1 AND 100),
  outcome          TEXT    NOT NULL CHECK (outcome IN (
                     'delivered_to_recipient', 'left_at_door', 'left_with_front_desk', 'left_with_neighbor', 'other')),
  -- Required explanation for 'other'; optional short note for the other exceptions.
  outcome_detail   TEXT    CHECK (outcome_detail IS NULL OR length(outcome_detail) BETWEEN 1 AND 300),
  note             TEXT    CHECK (note IS NULL OR length(note) BETWEEN 1 AND 500),
  -- Customer signature as validated PNG bytes. Served only through the API with Cache-Control: no-store.
  signature_png    BLOB    NOT NULL CHECK (length(signature_png) BETWEEN 67 AND 204800),
  signature_width  INTEGER NOT NULL CHECK (signature_width BETWEEN 100 AND 2400),
  signature_height INTEGER NOT NULL CHECK (signature_height BETWEEN 50 AND 1200),
  -- Decided by the server: only a hand-off to the recipient is 'confirmed'; every other outcome is saved as
  -- 'needs_review' until the shop defines which exceptions count as a completed delivery.
  result           TEXT    NOT NULL CHECK (result IN ('confirmed', 'needs_review')),
  -- Random key the driver's screen generates once per form, so a retried request never saves twice.
  idempotency_key  TEXT    NOT NULL UNIQUE CHECK (length(idempotency_key) = 36),
  -- SHA-256 of the submitted content: tells a true retry apart from a different submission reusing a key.
  request_hash     TEXT    NOT NULL CHECK (length(request_hash) = 64),
  -- Server time (UTC). The browser never supplies it.
  confirmed_at     TEXT    NOT NULL,
  CHECK (outcome <> 'other' OR outcome_detail IS NOT NULL),
  CHECK ((outcome = 'delivered_to_recipient') = (result = 'confirmed'))
);
CREATE INDEX idx_confirmations_confirmed_at ON delivery_confirmations(confirmed_at);

-- Submissions refused because the order already had a confirmation. Shown to employees as review flags.
-- 'duplicate' = same content submitted again (e.g. from a second tab); 'conflict' = different content.
-- Only the outcome and the received-by name of the refused attempt are kept (no signature).
CREATE TABLE confirmation_attempts (
  id               INTEGER PRIMARY KEY AUTOINCREMENT,
  confirmation_id  TEXT    NOT NULL REFERENCES delivery_confirmations(id) ON DELETE CASCADE,
  kind             TEXT    NOT NULL CHECK (kind IN ('duplicate', 'conflict')),
  received_by      TEXT    CHECK (received_by IS NULL OR length(received_by) <= 100),
  outcome          TEXT    CHECK (outcome IS NULL OR outcome IN (
                     'delivered_to_recipient', 'left_at_door', 'left_with_front_desk', 'left_with_neighbor', 'other')),
  created_at       TEXT    NOT NULL
);
CREATE INDEX idx_confirmation_attempts_confirmation ON confirmation_attempts(confirmation_id, created_at);

-- Fixed-window request counters for rate limiting. `bucket` is "<scope>:<HMAC of the client IP>", never the IP.
CREATE TABLE rate_limits (
  bucket        TEXT    NOT NULL,
  window_start  INTEGER NOT NULL,
  hits          INTEGER NOT NULL,
  PRIMARY KEY (bucket, window_start)
);
